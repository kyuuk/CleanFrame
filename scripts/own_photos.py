"""Overlay the owner's own wallpapers, built by `npm run photos`, into a personal build.

Originals and generated JPEGs stay in ignored .local/photos/. The public source
ships an empty own-catalog.js; a public export never reads this folder.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
IMAGE_SUFFIXES = {'.jpg', '.jpeg', '.png'}
EMPTY = b'/* No own wallpapers. A personal build replaces this from .local/photos. */\nwindow.CleanFrameOwnWallpapers = [];\nwindow.CleanFrameHideBundled = false;\n'


def photo_folder(root=ROOT):
    return root / '.local/photos'


def source_photos(root=ROOT):
    folder = photo_folder(root)
    if not folder.is_dir():
        return []
    return sorted(p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES)


def settings(root=ROOT):
    path = photo_folder(root) / 'cleanframe.json'
    return json.loads(path.read_text()) if path.is_file() else {}


def photo_overlay(root=ROOT, include_private=True):
    """Return package-relative paths mapped to bytes or built files."""
    if not include_private:
        return {'assets/wallpapers/own-catalog.js': EMPTY}
    build = photo_folder(root) / 'build'
    manifest_path = build / 'manifest.json'
    sources = source_photos(root)
    hide = bool(settings(root).get('hideBundled'))
    if not manifest_path.is_file():
        if sources:
            raise ValueError('Photos in .local/photos have not been built. Run: npm run photos')
        if hide:
            raise ValueError('hideBundled is set in .local/photos/cleanframe.json, but there are no own photos.')
        return {'assets/wallpapers/own-catalog.js': EMPTY}
    manifest = json.loads(manifest_path.read_text())
    built = {(p['source'], p['sourceBytes'], p['sourceMtime']) for p in manifest['photos']}
    current = {(p.name, p.stat().st_size, int(p.stat().st_mtime)) for p in sources}
    if built != current or hide != manifest['hideBundled']:
        raise ValueError('.local/photos changed since the last build. Run: npm run photos')
    if hide and not manifest['photos']:
        raise ValueError('hideBundled is set in .local/photos/cleanframe.json, but there are no own photos.')
    assets = {}
    for name in manifest['files']:
        path = (build / name).resolve()
        if not path.is_relative_to(build.resolve()) or not path.is_file():
            raise ValueError('Missing built photo file: ' + name)
        assets[name] = path
    entries = [p['entry'] for p in manifest['photos']]
    assets['assets/wallpapers/own-catalog.js'] = ('/* Generated by npm run photos from .local/photos. */\n'
        'window.CleanFrameOwnWallpapers = ' + json.dumps(entries, indent=2) + ';\n'
        'window.CleanFrameHideBundled = ' + json.dumps(hide) + ';\n').encode()
    return assets
